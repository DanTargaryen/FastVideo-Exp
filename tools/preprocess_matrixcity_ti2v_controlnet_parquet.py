def main() -> None:
    os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")
    os.environ.setdefault("OPENCV_IO_ENABLE_OPENEXR", "1")

    args = parse_args()
    env_world_size = int(os.environ.get("WORLD_SIZE", "1"))
    env_rank = int(os.environ.get("RANK", "0"))
    env_local_rank = int(os.environ.get("LOCAL_RANK", "0"))
    # Support torchrun: when user does not explicitly pass rank/world_size,
    # inherit from distributed env vars.
    if env_world_size > 1:
        if int(args.world_size) == 1:
            args.world_size = env_world_size
        if int(args.rank) == 0:
            args.rank = env_rank

    if int(args.world_size) <= 0:
        raise ValueError("--world_size must be >= 1")
    if int(args.rank) < 0 or int(args.rank) >= int(args.world_size):
        raise ValueError(f"--rank must be in [0,{int(args.world_size)-1}]")
    if float(args.online_warp_pose_filter_translation_ratio) < 0.0:
        raise ValueError("--online_warp_pose_filter_translation_ratio must be >= 0")
    if float(args.online_warp_pose_filter_max_rotation_deg) < 0.0:
        raise ValueError("--online_warp_pose_filter_max_rotation_deg must be >= 0")

    model_path = os.path.expanduser(os.path.expandvars(args.model_path))
    mask_root = (
        Path(os.path.expanduser(os.path.expandvars(args.mask_root)))
        if str(args.mask_root).strip()
        else None
    )
    rgb_root = Path(os.path.expanduser(os.path.expandvars(args.rgb_root)))
    depth_root = Path(os.path.expanduser(os.path.expandvars(args.depth_root))) if str(args.depth_root).strip() else rgb_root
    output_dir = Path(os.path.expanduser(os.path.expandvars(args.output_dir)))
    normal_root = Path(os.path.expanduser(os.path.expandvars(args.normal_root))) if str(args.normal_root).strip() else None
    control_source = str(args.control_source).strip().lower()
    precomputed_layout = str(args.precomputed_layout).strip().lower()
    output_dir.mkdir(parents=True, exist_ok=True)

    if control_source == "online_warp" and bool(args.require_masked_rgb):
        logger.warning(
            "--require_masked_rgb is ignored when control_source=online_warp because masked_rgb is generated on the fly."
        )
    if bool(args.bootstrap_only) and bool(args.require_masked_rgb):
        logger.warning(
            "--require_masked_rgb is ignored when --bootstrap_only is enabled because control latents are not precomputed."
        )
    if (bool(args.bootstrap_only)
            and bool(args.bootstrap_cache_first_window_control_latent)
            and control_source != "online_warp"):
        logger.warning(
            "--bootstrap_cache_first_window_control_latent is ignored unless "
            "--bootstrap_only and --control_source=online_warp are both enabled."
        )
    if control_source == "online_warp" and str(args.first_frame_source) == "masked_rgb":
        logger.info(
            "control_source=online_warp with first_frame_source=masked_rgb: first frame remains equivalent to rgb because frame0 mask is forced visible."
        )
    if control_source == "precomputed" and mask_root is None:
        raise ValueError("--mask_root is required when control_source=precomputed")
    if bool(args.bootstrap_only) and str(args.first_frame_source) == "masked_rgb":
        logger.warning(
            "--bootstrap_only with first_frame_source=masked_rgb falls back to rgb first frame because masked_rgb is not loaded."
        )

    if args.device == "cuda" and torch.cuda.is_available():
        # torchrun: use LOCAL_RANK; manual CUDA_VISIBLE_DEVICES per process: local rank defaults to 0.
        device = torch.device(f"cuda:{env_local_rank}")
        torch.cuda.set_device(env_local_rank)

        # Some FastVideo layers (e.g., vocab-parallel embedding) expect TP/SP groups
        # to be initialized even in single-process mode.
        # torchrun mode: use env:// shared rendezvous.
        # standalone per-process mode: use unique tcp:// port per shard.
        if env_world_size > 1:
            dist_init_method = "env://"
        else:
            dist_port = 29500 + int(args.rank)
            dist_init_method = f"tcp://127.0.0.1:{dist_port}"
        maybe_init_distributed_environment_and_model_parallel(
            tp_size=1,
            sp_size=1,
            distributed_init_method=dist_init_method,
        )
    else:
        device = torch.device("cpu")
    compute_dtype = _to_torch_dtype(str(args.dtype))

    pipeline_config = PipelineConfig.from_pretrained(model_path)
    fastvideo_args = FastVideoArgs(
        model_path=model_path,
        num_gpus=1,
        dit_cpu_offload=False,
        vae_cpu_offload=False,
        text_encoder_cpu_offload=False,
        pipeline_config=pipeline_config,
    )

    text_encoder = PipelineComponentLoader.load_module(
        module_name="text_encoder",
        component_model_path=os.path.join(model_path, "text_encoder"),
        transformers_or_diffusers="transformers",
        fastvideo_args=fastvideo_args,
    ).to(device)
    tokenizer = PipelineComponentLoader.load_module(
        module_name="tokenizer",
        component_model_path=os.path.join(model_path, "tokenizer"),
        transformers_or_diffusers="transformers",
        fastvideo_args=fastvideo_args,
    )
    vae = PipelineComponentLoader.load_module(
        module_name="vae",
        component_model_path=os.path.join(model_path, "vae"),
        transformers_or_diffusers="diffusers",
        fastvideo_args=fastvideo_args,
    ).to(device)
    text_stage = TextEncodingStage(text_encoders=[text_encoder], tokenizers=[tokenizer])

    z_dim = getattr(vae, "z_dim", None)
    if z_dim is None:
        z_dim = getattr(getattr(vae, "config", None), "z_dim", None)
    if z_dim is None:
        z_dim = 16
    if int(args.target_num_channels_latents) > 0:
        target_num_channels_latents = int(args.target_num_channels_latents)
        if target_num_channels_latents < int(z_dim):
            logger.warning(
                "target_num_channels_latents=%d < z_dim=%d; forcing to z_dim to avoid truncation.",
                int(target_num_channels_latents),
                int(z_dim),
            )
            target_num_channels_latents = int(z_dim)
    else:
        target_num_channels_latents = _infer_target_num_channels_latents(
            model_path, int(z_dim)
        )
    if int(args.latent_repeat) > 0:
        latent_repeat = int(args.latent_repeat)
    else:
        if int(z_dim) > 0 and target_num_channels_latents % int(z_dim) == 0:
            latent_repeat = target_num_channels_latents // int(z_dim)
        else:
            latent_repeat = _infer_latent_repeat(model_path, int(z_dim))
    latent_repeat = max(1, int(latent_repeat))
    logger.info(
        "VAE z_dim=%d target_num_channels_latents=%d latent_repeat=%d",
        int(z_dim),
        int(target_num_channels_latents),
        int(latent_repeat),
    )

    out_dir_rank = output_dir / f"rank_{int(args.rank):02d}"
    writer = ParquetDatasetWriter(str(out_dir_rank), samples_per_file=int(args.samples_per_file))
    buffer: list[dict[str, Any]] = []
    existing_ids: set[str] = set()
    # Cache per-street sequence file lists to avoid repeated expensive directory scans.
