"""
Preprocess InteriorNet mask clips + captions into FastVideo TI2V+ControlNet parquet.

This mirrors the core encoding logic in:
  fastvideo/pipelines/preprocess/v1_preprocess_omnigame_ti2v_controlnet.py

Input layout (MASK_INTERIORNET):
  <mask_root>/<scene_key>/<window_start>_<window_end>/clip_start_XXX/
      mask/*.png
      masked_rgb/*.png   (optional; if missing, will fall back to rgb * mask)
      caption_*.json     (generated by tools/qwen_caption_interiornet_clips.py)

RGB/Depth layout (DATA_INTERIORNET):
  <data_root>/<HD>/<SCENE_ID>/<SEQ>/cam0/data/*.(webp|png|jpg)
  <data_root>/<HD>/<SCENE_ID>/<SEQ>/depth0/data/*.(png|exr)

Alignment convention (same as our caption script / UniDataset loader intent):
  global_idx = window_start + clip_start + local_idx
where local_idx is 0..clip_length-1.

Output:
  <output_dir>/rank_XX/worker_*/data_chunk_*.parquet compatible with
  fastvideo.dataset.dataloader.schema.py: pyarrow_schema_ti2v_controlnet
"""

