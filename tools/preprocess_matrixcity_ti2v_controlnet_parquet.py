def _slice_by_id_or_index(files: list[Path], start: int, end: int) -> list[Path]:
    if not files:
        return []
    n = len(files)
    # Prefer id-range when numeric frame ids are available and overlap exists.
    # This avoids cross-modality drift when some modalities have dropped frames.
    parsed_ids = [_frame_index_from_stem(p.stem) for p in files]
    if all(fid is not None for fid in parsed_ids):
        ids = [int(fid) for fid in parsed_ids]
        lo = None
        hi = None
        # find first >= start and last <= end
        for i, fid in enumerate(ids):
            if lo is None and fid >= start:
                lo = i
            if fid <= end:
                hi = i
        if lo is not None and hi is not None and lo <= hi:
            return files[lo:hi + 1]
    # fallback index-range
    if 0 <= start <= end < n:
        return files[start:end + 1]
    return []


def _resolve_clip_start_offset(
    window_files: list[Path],
    clip_start: int,
    window_start: int,
) -> int:
    """
    Convert clip_start to window-relative offset.

    MatrixCity mask clips usually name clip_start as absolute frame id/index in the
    full street sequence, while this script slices from per-window lists. This
    helper maps clip_start to the correct offset in window_files.
    """
    if not window_files:
        return 0

    # Prefer frame-id alignment when filenames carry numeric frame ids.
    parsed_ids = [_frame_index_from_stem(p.stem) for p in window_files]
    if all(fid is not None for fid in parsed_ids):
        ids = [int(fid) for fid in parsed_ids]
        # Use the first frame whose id is >= clip_start.
        for i, fid in enumerate(ids):
            if fid >= int(clip_start):
                return i
        # clip_start is after window tail: extrapolate so caller can pad.
        return max(0, int(clip_start) - int(ids[0]))

    # Fallback for non-numeric names:
    # treat clip_start as global index first; if invalid, treat as local offset.
    rel = int(clip_start) - int(window_start)
    if rel < 0:
        rel = int(clip_start)
    return max(0, rel)


def _resolve_clip_start_global_id_for_sampling(
    *,
    clip_start: int,
    window_start: int,
    window_end: int,
) -> tuple[int, str]:
    """
    Resolve clip_start semantics for global-id sampling.

    MatrixCity variants are inconsistent:
    - some clips use global frame id in clip_start_XXXX
    - some clips use window-local offset (relative to window_start)

    We auto-correct local-offset cases following UniDataset MatrixCity scripts:
    - clip_start is sampled within current window sequence (local offset),
      then saved as clip_start_XXX.
    - if `clip_start` is in [0, window_len), treat it as local offset and
      convert to global id by `window_start + clip_start`.
    - otherwise, keep it as global id.
    """
    cs = int(clip_start)
    ws = int(window_start)
    we = int(window_end)
    window_len = max(1, int(we) - int(ws) + 1)
    if 0 <= cs < window_len:
        return ws + cs, "local_offset_window"
    if cs < ws:
        # Legacy fallback for malformed naming.
        return ws + cs, "local_offset_legacy"
    # keep original behavior for global-id naming
    return cs, "global_id"


