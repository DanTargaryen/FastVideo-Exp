"""
Preprocess MatrixCity mask clips + captions into FastVideo TI2V+ControlNet parquet.

Input layout (MASK_MATRIXCITY):
  <mask_root>/<street_dir>/<window_start>_<window_end>/clip_start_XXX/
      mask/*.png
      masked_rgb/*.png   (optional; if missing, will fall back to rgb * mask)
      caption_*.json     (generated by a Qwen caption script)

RGB layout (DATA_MATRIXCITY, RGB only):
  <rgb_root>/small_city/street/<street_split>/<street_dir>/<street_dir>/*.png

Depth layout options:
  1) If you have a "small_city_depth" dataset (EXR), pass --depth_root pointing to the
     root that contains "small_city_depth/..." and we will try to locate the aligned
     depth folder. (EXR decoding requires OpenCV EXR enabled.)
  2) If you already have per-frame depth PNGs aligned to RGB, you can point --depth_dir
     directly to that folder and skip auto-derivation.

Window interpretation:
  - If window_start/window_end are valid indices into the sorted RGB list, treat as index range.
  - Otherwise, treat as "frame id range" (stems); this script will slice by id.

If the window range is shorter than needed (common in MatrixCity masks), the script pads by
repeating the last frame, matching the dataset's typical padding behavior.
"""

