def _to_torch_dtype(dtype_str: str) -> torch.dtype:
    s = str(dtype_str).strip().lower()
    if s == "bf16":
        return torch.bfloat16
    if s == "fp16":
        return torch.float16
    return torch.float32


def _load_existing_ids(parquet_rank_dir: Path) -> set[str]:
    ids: set[str] = set()
    if not parquet_rank_dir.is_dir():
        return ids
    for pf in sorted(parquet_rank_dir.rglob("*.parquet")):
        try:
            table = pq.read_table(str(pf), columns=["id"])
            col = table.column("id").to_pylist()
            for x in col:
                if x is not None:
                    ids.add(str(x))
        except Exception as e:
            logger.warning("Failed to read existing ids from %s: %s", pf, e)
    return ids


def _prompt_clean(text: str) -> str:
    text = ftfy.fix_text(str(text))
    text = html.unescape(html.unescape(text))
    text = re.sub(r"\s+", " ", text).strip()
    return text


def _read_caption_json(path: Path, caption_key: str) -> str:
    obj = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(obj, dict) and "captions" in obj and isinstance(obj["captions"], dict):
        caps = obj["captions"]
    else:
        caps = obj

    if caption_key:
        v = caps.get(caption_key, "")
        if isinstance(v, str) and v.strip():
            return v.strip()

    for k in ("Video_Caption", "Short_Caption", "PC_Caption", "caption", "text", "prompt", "description"):
        v = caps.get(k, "")
        if isinstance(v, str) and v.strip():
            return v.strip()
    return ""


